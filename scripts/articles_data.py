def inline(t):
    t = html.escape(t, quote=False)
    return re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+?)(?:\?utm_source=[^)\s]*)?\)", r'<a href="\2" rel="noopener" target="_blank">\1</a>', t)


def convert_md(path):
    raw = open(path, encoding="utf-8").read()
    raw = raw.replace("בלי להגביר את הלחץ", "בלי להגביר את המתח")
    faq_m = re.search(r"### שאלות ותשובות נפוצות \(FAQ\)(.*?)### קריאה לפעולה", raw, re.S)
    src_m = re.search(r"### מקורות מקצועיים למחקר(.*)$", raw, re.S)
    first = raw.index("### מהי חרדה חברתית")
    intro_raw = raw[raw.index("\n", raw.index("מאמר SEO")):first]
    cut_end = raw.index("### חבילת SEO") if "### חבילת SEO" in raw else len(raw)
    body_raw = raw[first:cut_end]
    # הסרת אזורי FAQ, CTA ומקורות מהגוף
    body_raw = re.sub(r"### שאלות ותשובות נפוצות \(FAQ\).*$", "", body_raw, flags=re.S)
    body_raw = re.sub(r"### קריאה לפעולה.*$", "", body_raw, flags=re.S)
    intro = [clean(p) for p in re.split(r"\n\s*\n", intro_raw) if p.strip()]
    out, toc, lis = [], [], []
    def flush():
        nonlocal lis
        if lis:
            out.append("<ul class=\"list\">" + "".join(f"<li>{inline(x)}</li>" for x in lis) + "</ul>")
            lis = []
    for line in body_raw.split("\n"):
        l = line.strip()
        if not l:
            continue
        if l.startswith("### "):
            flush(); h = clean(l[4:])
            if re.match(r"^\d+\.?\s", h):
                out.append(f"<h3>{inline(re.sub(r'^\d+\.?\s*', '', h))}</h3>")
            else:
                i = len(toc) + 1; toc.append((f"s{i}", h)); out.append(f'<h2 id="s{i}">{inline(h)}</h2>')
        elif l.startswith("* "):
            lis.append(clean(l[2:]))
        elif re.match(r"^שלב (ראשון|שני|שלישי|רביעי|חמישי) –", l):
            flush(); out.append(f"<h3>{inline(clean(l))}</h3>")
        else:
            flush(); out.append(f"<p>{inline(clean(l))}</p>")
    flush()
    faq = []
    if faq_m:
        for m in re.finditer(r"^\d+\\?\.\s*(.+?)\n\s*\n(.+?)(?=\n\s*\n\d+\\?\.|\Z)", faq_m.group(1).strip() + "\n", re.S | re.M):
            faq.append((clean(m.group(1)), clean(m.group(2).replace("\n", " "))))
    sources = []
    if src_m:
        for m in re.finditer(r"^\d+\\?\.\s*(.+)$", src_m.group(1), re.M):
            sources.append(clean(m.group(1)))
    return intro, "".join(out), toc, faq, sources


