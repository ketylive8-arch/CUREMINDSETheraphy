def esc(s):
    return html.escape(s, quote=False)

def render(body):
    out = []
    for block in body.strip().split('\n'):
        s = block.rstrip()
        t = s.strip()
        if not t:
            continue
        if t.startswith('## '):
            out.append(f'<h2>{esc(t[3:])}</h2>')
        elif t.startswith('### '):
            out.append(f'<h3>{esc(t[3:])}</h3>')
        elif t.startswith('- '):
            out.append(f'<li>{esc(t[2:])}</li>')
        elif re.match(r'^\d+\.\s', t):
            stripped = re.sub(r'^\d+\.\s', '', t)
            out.append('<li>' + esc(stripped) + '</li>')
        else:
            out.append(f'<p>{esc(t)}</p>')
    # איחוד li עוקבים לרשימה אחת
    html_out, in_ul = [], False
    for item in out:
        if item.startswith('<li>'):
            if not in_ul:
                html_out.append('<ul class="bullets">')
                in_ul = True
            html_out.append(item)
        else:
            if in_ul:
                html_out.append('</ul>')
                in_ul = False
            html_out.append(item)
    if in_ul:
        html_out.append('</ul>')
    return '\n'.join(html_out)

def page(filename, title, description, canonical, eyebrow, h1, lead, body, extra_cta=''):
    head = prefix
    head = re.sub(r'<title>.*?</title>', f'<title>{esc(title)}</title>', head, flags=re.S)
    head = re.sub(r'<meta name="description" content=".*?" />',
                  f'<meta name="description" content="{esc(description)}" />', head, flags=re.S)
    head = re.sub(r'<link rel="canonical" href=".*?" />',
                  f'<link rel="canonical" href="https://www.ketysegev.com/{canonical}" />', head, flags=re.S)
    head = re.sub(r'<meta property="og:title" content=".*?" />',
                  f'<meta property="og:title" content="{esc(title)}" />', head, flags=re.S)
    head = re.sub(r'<meta property="og:description" content=".*?" />',
                  f'<meta property="og:description" content="{esc(description)}" />', head, flags=re.S)
    # כל כפתורי התשלום/פגישה מצביעים למערכת המזכירה
    head = head.replace('https://calendly.com/ketysegev/meet-with-me', BOOK)

    main = (
        '<main id="main" class="wrap" data-sc-in data-sc-stagger="70">'
        '<section class="hero"><div class="hero-grid"><div>'
        f'<p class="eyebrow">{esc(eyebrow)}</p><h1>{esc(h1)}</h1>'
        + (f'<p class="lead">{esc(lead)}</p>' if lead else '') +
        f'<div class="btnrow"><a class="btn primary" href="{BOOK}" target="_blank" rel="noopener">לקביעת פגישה</a>'
        f'<a class="btn ghost" href="{WA}" target="_blank" rel="noopener">וואטסאפ</a></div>'
        '</div></div></section>'
        '<section class="body-sec">' + render(body) + '</section>'
        + extra_cta +
        '</main>'
    )
    out_suffix = suffix.replace('https://calendly.com/ketysegev/meet-with-me', BOOK)
    open(filename, 'w', encoding='utf-8').write(head + main + out_suffix)
    print('built', filename)

