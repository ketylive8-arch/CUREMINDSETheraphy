    fig = f'<figure><img src="{photo}" alt="{esc(alt)}" width="640" height="800" fetchpriority="high"></figure>' if photo else ""
    cls = "hero photo" if photo else "hero"
    return f'''<section class="{cls}"><div class="wrap hero-in"><div><h1>{h1}</h1><p class="lead">{lead}</p>{ps}{extra_btns or btns()}</div>{fig}</div></section>'''


