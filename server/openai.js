class NoApiKeyError extends Error {
  constructor() {
    super("OPENAI_API_KEY is not configured on the server");
  }
}

// Maps a journey day (1-14+) to its gate so the model anchors the whole reply to it.
function journeyContext(journeyDay) {
  if (!journeyDay) return "";
  if (journeyDay > 14) {
    return `\n[הקשר מסע: המשתמש/ת סיימ/ה את 14 ימי המסע ונמצא/ת בשלב השימור וההעמקה (מנוי). יום ${journeyDay} מתחילת הדרך.]`;
  }
  const gate =
    journeyDay <= 3 ? "שער 1 — חוסן רגשי ועוגן" :
    journeyDay <= 7 ? "שער 2 — דימוי עצמי" :
    journeyDay <= 11 ? "שער 3 — ביטחון פנימי" :
    "שער 4 — עבודה עם חרדה ושימור";
  return `\n[הקשר מסע: יום ${journeyDay} מתוך 14 — ${gate}. התאם/י את התגובה והמשימה היומית לשער הזה.]`;
}

async function runBehavioralHealthCheck(text, ageGroup = "adult", journeyDay = null) {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) throw new NoApiKeyError();

  const systemPrompt = (ageGroup === "youth" ? SYSTEM_PROMPT_YOUTH : SYSTEM_PROMPT_ADULT) + journeyContext(journeyDay);

  const response = await fetch("https://api.openai.com/v1/chat/completions", {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Authorization: `Bearer ${apiKey}`,
    },
    body: JSON.stringify({
      model: "gpt-4o-mini",
      response_format: { type: "json_object" },
      temperature: 0.72,
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: text },
      ],
    }),
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`OpenAI request failed: ${response.status} ${body}`);
  }

  const data = await response.json();
  const raw = data.choices?.[0]?.message?.content || "{}";
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch {
    parsed = { reply: raw, extraction: {} };
  }

  const extraction = parsed.extraction || {};
  return {
    reply: typeof parsed.reply === "string" ? parsed.reply : "",
    dailyTask: parsed.dailyTask && typeof parsed.dailyTask.title === "string" ? parsed.dailyTask : null,
    triggers: Array.isArray(extraction.triggers) ? extraction.triggers : [],
    patterns: Array.isArray(extraction.patterns) ? extraction.patterns : [],
    balanceAlerts: Array.isArray(extraction.balanceAlerts) ? extraction.balanceAlerts : [],
    wins: Array.isArray(extraction.wins) ? extraction.wins : [],
  };
}

