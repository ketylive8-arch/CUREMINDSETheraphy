// שיקוף קצר לפי עוצמת ההודעה — מוסיף תחושה שבאמת הקשבתי.
const REFLECT_STRONG = ["אני שומע/ת שזה ממש כבד עכשיו.", "זה נשמע מציף, ואת/ה לא לבד בזה."];
function isStrong(text) {
  return /(מאוד|נורא|קשה מאוד|לא יכול|בוכ|מתמוטט|נשבר|באמת קשה|הכי גרוע|רוצה לוותר)/.test(String(text || ""));
}
function isGreeting(text) {
  const t = String(text || "").trim();
  return t.length <= 6 && /(היי|הי|שלום|בוקר|ערב|היא)/.test(t);
}

// גיבוב יציב מהטקסט — כדי שהודעות שונות יקבלו וריאציות שונות (לא רק לפי שעה).
function hash(s) {
  let h = 0;
  const str = String(s || "");
  for (let i = 0; i < str.length; i++) h = (h * 31 + str.charCodeAt(i)) | 0;
  return Math.abs(h);
}
function pick(arr, seed) {
  return arr[Math.abs(seed) % arr.length];
}
function pickTheme(text) {
  const t = String(text || "");
  for (const th of THEMES) if (th.keys.some((k) => t.includes(k))) return th;
  return null;
}
function firstNameFrom(userProfile) {
  const m = String(userProfile || "").match(/שם:\s*([^·|\n]+)/);
  if (!m) return "";
  const full = m[1].trim();
  if (!full || full === "—") return "";
  return full.split(/\s+/)[0].slice(0, 20);
}
// משפט קצר ורלוונטי מתוך ידע השיטה (RAG), אם יש — מוסיף עומק מתודי.
function knowledgeLine(retrieved) {
  if (!Array.isArray(retrieved) || !retrieved.length) return "";
  const txt = String(retrieved[0].text || retrieved[0].content || retrieved[0].snippet || "");
  const sent = txt
    .split(/\n+|(?<=[.!?׃])\s+/)
    .map((s) => s.replace(/^[#>*\-\d.\s]+/, "").trim()) // מסיר סימוני markdown/מספור בתחילת שורה
    .filter((s) => s.length > 30 && s.length < 180 && /[א-ת]/.test(s) && /[.!?]$/.test(s));
  return sent[0] || "";
}

function guidedReply(text, retrieved, userProfile) {
  const h = hash(text);
  const th = pickTheme(text) || pickTheme(userProfile);
  const name = firstNameFrom(userProfile);

  // ברכה קצרה בלבד → מגיבים בחום ומזמינים לשתף.
  if (isGreeting(text)) {
    const g = name ? `היי ${name} 🌿 טוב שאת/ה כאן.` : "היי 🌿 טוב שאת/ה כאן.";
    return {
      reply: `${g} איך את/ה מרגיש/ה ברגע הזה? ספר/י לי מה עובר עלייך — אני מקשיב/ה.`,
      dailyTask: { title: "רגע של נוכחות", description: "נשימה עמוקה אחת, ומשפט: \"אני כאן\".", category: "mindfulness" },
      triggers: [], patterns: [], balanceAlerts: [], wins: [], via: "guided-local",
    };
  }

  const opener = pick(OPENERS, h);
  const parts = [name ? `${name}, ${opener}` : opener];
  if (isStrong(text)) parts.push(pick(REFLECT_STRONG, h + 1));

  if (th) {
    parts.push(th.mechanism);
    parts.push("בשיטת CureMindset: " + pick(th.tools, h + 2));
    const kl = knowledgeLine(retrieved);
    if (kl) parts.push(kl);
    parts.push(pick(th.followups, h + 5)); // שאלת המשך — ממשיך את השיחה
  } else {
    parts.push("בשיטת CureMindset אנחנו עובדים עם השורש הרגשי, לא רק עם התסמין.");
    const kl = knowledgeLine(retrieved);
    if (kl) parts.push(kl);
    parts.push("ספר/י לי עוד — איפה בגוף את/ה מרגיש/ה את זה עכשיו, ומה המחשבה שרצה שם ברגע הזה?");
  }
  parts.push(pick(CLOSERS, h + 7));

  return {
    reply: parts.join(" "),
    dailyTask: th ? th.task : { title: "רגע של קרקוע", description: "שלוש נשימות עמוקות ומשפט: \"אני כאן, ברגע הזה\".", category: "mindfulness" },
    triggers: [],
    patterns: th ? [{ title: th.label, description: th.mechanism }] : [],
    balanceAlerts: [],
    wins: [],
    via: "guided-local",
  };
}

