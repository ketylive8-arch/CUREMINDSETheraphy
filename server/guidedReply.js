function isStrong(text) {
  return /(מאוד|נורא|קשה מאוד|לא יכול|בוכ|מתמוטט|נשבר|באמת קשה|הכי גרוע|רוצה לוותר|אין לי כוח)/.test(String(text || ""));
}
